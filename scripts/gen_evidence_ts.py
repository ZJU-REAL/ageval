"""Generate the shared TypeScript for sealed evidence documents.

The Python dataclasses in ``ageval.evidence.documents`` are the contract.
This script writes JSON Schema into ``apps/shared/lib/evidence.gen.ts`` and
the types that schema describes. ``--check`` fails when the file drifts.
Do not hand-write a second copy of the same wire shapes.

    python scripts/gen_evidence_ts.py --write
    python scripts/gen_evidence_ts.py --check
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from ageval.evidence.documents import json_schema  # noqa: E402

OUT = ROOT / "apps" / "shared" / "lib" / "evidence.gen.ts"
_HEADER = """\
// Generated by scripts/gen_evidence_ts.py. Do not edit.
// Wire documents for summary.json, result.json, and the trajectory terminal row.
// Display projections (input_tokens / output_tokens) stay in the trial view model.

"""


def _ref_name(node: dict[str, Any]) -> str:
    return str(node["$ref"]).rsplit("/", 1)[-1]


def _ts_type(node: dict[str, Any]) -> str:
    if "anyOf" in node:
        return " | ".join(_ts_type(part) for part in node["anyOf"])
    if "oneOf" in node:
        return " | ".join(_ts_type(part) for part in node["oneOf"])
    if "$ref" in node:
        return _ref_name(node)
    if "const" in node:
        return json.dumps(node["const"])
    if "enum" in node:
        return " | ".join(json.dumps(item) for item in node["enum"])
    kind = node.get("type")
    if kind == "string":
        return "string"
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    if kind == "array":
        item = _ts_type(node["items"])
        if "|" in item:
            item = f"({item})"
        return f"{item}[]"
    if kind == "object" and "properties" not in node:
        return "Record<string, unknown>"
    raise TypeError(f"cannot render schema node as TypeScript: {node!r}")


def _interface(name: str, node: dict[str, Any]) -> str:
    required = set(node.get("required", ()))
    lines = [f"export interface {name} {{"]
    for key, prop in node["properties"].items():
        optional = "" if key in required else "?"
        lines.append(f"  {key}{optional}: {_ts_type(prop)};")
    lines.append("}")
    return "\n".join(lines)


def _alias(name: str, node: dict[str, Any]) -> str:
    return f"export type {name} = {_ts_type(node)};"


def render_ts(schema: dict[str, Any] | None = None) -> str:
    document = schema if schema is not None else json_schema()
    blocks: list[str] = []
    for name in sorted(document["$defs"]):
        node = document["$defs"][name]
        if node.get("type") == "object" and "properties" in node:
            blocks.append(_interface(name, node))
        elif "oneOf" in node:
            blocks.append(_alias(name, node))
        else:
            raise TypeError(f"unsupported definition {name}")
    schema_json = json.dumps(document, indent=2, sort_keys=True)
    blocks.append(f"export const evidenceJsonSchema = {schema_json} as const;")
    return _HEADER + "\n\n".join(blocks) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--check", action="store_true")
    group.add_argument("--write", action="store_true")
    args = parser.parse_args(argv)
    rendered = render_ts()
    current = OUT.read_text(encoding="utf-8") if OUT.is_file() else ""
    if args.write:
        if current != rendered:
            OUT.parent.mkdir(parents=True, exist_ok=True)
            OUT.write_text(rendered, encoding="utf-8")
        return 0
    if current != rendered:
        print(f"evidence typescript drifted: {OUT.relative_to(ROOT)}", file=sys.stderr)
        print("run: python scripts/gen_evidence_ts.py --write", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
